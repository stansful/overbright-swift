#!/usr/bin/env bash
# SDK name-collision probe (ARCHITECTURE.md §8.7, §9.2 rule 4). Regenerates one probe per target that other modules
# import everywhere:
#   Packages/OverbrightKit/Tests/OverbrightCoreTests/SDKNameCollisionProbe.swift     (OverbrightCore's names)
#   Packages/OverbrightKit/Tests/OverbrightPolicyTests/SDKNameCollisionProbe.swift   (OverbrightPolicy's names)
#   Packages/OverbrightKit/Tests/OverbrightDesignTests/SDKNameCollisionProbe.swift   (OverbrightDesign's names: every UI
#                                                                                    module imports it with SwiftUI;
#                                                                                    added by WP13 after WP9's note)
# Each file imports every Apple framework the modules use plus the module (Policy's also Core) and aliases every
# top-level public type. A name that an SDK also exports (`Clock`, `Settings`) becomes an "ambiguous" compile error in
# `swift test`, before any module trips over it. Each probe lives in its own module's test target, so each owner
# regenerates only its own file.
#
#   scripts/name-probe.sh            # regenerate after adding public Core or Policy types (commit the result)
#   CHECK=1 scripts/name-probe.sh    # fail if a committed probe is out of date (CI)
source "$(dirname "$0")/lib.sh"
# The output is committed and compared byte for byte (CHECK=1): sort the same way in every locale
# (CI images export LC_ALL=en_US.UTF-8; contributors may run ru_RU.UTF-8, whose collation differs from C).
export LC_ALL=C

FRAMEWORKS=(AppIntents AppKit AVFoundation Carbon ColorSync CoreGraphics CoreMedia CoreMediaIO CoreVideo Foundation
            IOKit Metal QuartzCore ServiceManagement SwiftUI UniformTypeIdentifiers WidgetKit Observation os)

# $1 = module, $2 = extra modules to import (space-separated, may be empty)
generate() {
  local module="$1" extra="$2" m
  echo "// GENERATED by scripts/name-probe.sh — do not edit. Regenerate after adding public $module types."
  echo "// Compiles only if no top-level public $module type name is ambiguous with an SDK type (ARCHITECTURE.md §9.2)."
  for m in "${FRAMEWORKS[@]}" $extra "$module"; do echo "import $m"; done
  echo
  # Top-level public declarations only (nested types are namespaced). Generic types are skipped (they
  # need parameters); protocols are spelled `any P` (ExistentialAny).
  { grep -rhoE "^(@MainActor )?(@Observable )?(@MainActor )?public (nonisolated )?(final )?(struct|enum|class|protocol|actor|typealias) [A-Z][A-Za-z0-9]*<?" \
      "$PACKAGE_DIR/Sources/$module" || true; } |
    awk '{print $(NF-1), $NF}' | { grep -v '<$' || true; } | sort -k2 -u |
    while read -r kind name; do
      if [[ "$kind" == protocol ]]; then
        echo "private typealias Probe$name = any $name"
      else
        echo "private typealias Probe$name = $name"
      fi
    done
}

failed=0
for spec in "OverbrightCore:" "OverbrightPolicy:OverbrightCore" "OverbrightDesign:OverbrightCore OverbrightPolicy"; do
  module="${spec%%:*}"
  extra="${spec#*:}"
  probe="$PACKAGE_DIR/Tests/${module}Tests/SDKNameCollisionProbe.swift"
  tmp="$(mktemp)"
  generate "$module" "$extra" > "$tmp"
  if [[ "${CHECK:-0}" == 1 ]]; then
    if cmp -s "$tmp" "$probe"; then
      log "$module name-collision probe is up to date ($(grep -c '^private typealias' "$probe") names)"
    else
      warn "$probe is out of date"
      failed=1
    fi
  else
    cp "$tmp" "$probe"
    log "Wrote $probe ($(grep -c '^private typealias' "$probe") names); \`make test\` compiles it"
  fi
  rm -f "$tmp"
done
(( failed == 0 )) || die "name-collision probes are out of date; run scripts/name-probe.sh (make probe) and commit the result"
